static const uint8_t k_aes_rcon[11] = {
    0x8d, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
};

static inline uint8_t gf_xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ (((x >> 7) & 1u) * 0x1bu));
}

static inline uint8_t gf_mul(uint8_t x, uint8_t y) {
    uint8_t r = 0;
    for (int i = 0; i < 4; i++) {
        if (y & 1u) {
            r ^= x;
        }
        x = gf_xtime(x);
        y >>= 1;
    }
    return r;
}

static void aes128_expand_key(const uint8_t key[16], uint8_t rk[176]) {
    memcpy(rk, key, 16);
    uint8_t t[4];
    for (int i = 4; i < 44; i++) {
        memcpy(t, &rk[(i - 1) * 4], 4);
        if ((i & 3) == 0) {
            uint8_t u = t[0];
            t[0] = k_aes_sbox[t[1]] ^ k_aes_rcon[i >> 2];
            t[1] = k_aes_sbox[t[2]];
            t[2] = k_aes_sbox[t[3]];
            t[3] = k_aes_sbox[u];
        }
        for (int j = 0; j < 4; j++) {
            rk[i * 4 + j] = rk[(i - 4) * 4 + j] ^ t[j];
        }
    }
}

static void aes_add_round_key(uint8_t s[16], const uint8_t *rk) {
    for (int i = 0; i < 16; i++) {
        s[i] ^= rk[i];
    }
}

void sc21_aes128_ecb_encrypt(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[176];
    uint8_t s[16];
    aes128_expand_key(key, rk);
    memcpy(s, in, 16);
    aes_add_round_key(s, rk);

    for (int round = 1; round <= 10; round++) {
        /* SubBytes */
        for (int i = 0; i < 16; i++) {
            s[i] = k_aes_sbox[s[i]];
        }
        /* ShiftRows (column-major 4x4 state) */
        uint8_t tmp;
        tmp = s[1]; s[1] = s[5]; s[5] = s[9];  s[9]  = s[13]; s[13] = tmp;
        tmp = s[2]; s[2] = s[10]; s[10] = tmp;
        tmp = s[6]; s[6] = s[14]; s[14] = tmp;
        tmp = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = tmp;

        /* MixColumns */
        if (round < 10) {
            for (int c = 0; c < 16; c += 4) {
                uint8_t a0 = s[c + 0], a1 = s[c + 1], a2 = s[c + 2], a3 = s[c + 3];
                uint8_t xr = a0 ^ a1 ^ a2 ^ a3;
                s[c + 0] ^= xr ^ gf_xtime(a0 ^ a1);
                s[c + 1] ^= xr ^ gf_xtime(a1 ^ a2);
                s[c + 2] ^= xr ^ gf_xtime(a2 ^ a3);
                s[c + 3] ^= xr ^ gf_xtime(a3 ^ a0);
            }
        }
        aes_add_round_key(s, &rk[round * 16]);
    }
    memcpy(out, s, 16);
}

void sc21_aes128_ecb_decrypt(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[176];
    uint8_t s[16];
    aes128_expand_key(key, rk);
    memcpy(s, in, 16);
    aes_add_round_key(s, &rk[160]);

    for (int round = 9; round >= 0; round--) {
        /* InvShiftRows */
        uint8_t tmp;
        tmp = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = tmp;
        tmp = s[2]; s[2] = s[10]; s[10] = tmp;
        tmp = s[6]; s[6] = s[14]; s[14] = tmp;
        tmp = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = tmp;

        /* InvSubBytes */
        for (int i = 0; i < 16; i++) {
            s[i] = k_aes_rsbox[s[i]];
        }
        aes_add_round_key(s, &rk[round * 16]);

        /* InvMixColumns */
        if (round > 0) {
            for (int c = 0; c < 16; c += 4) {
                uint8_t a0 = s[c + 0], a1 = s[c + 1], a2 = s[c + 2], a3 = s[c + 3];
                s[c + 0] = gf_mul(a0, 0x0e) ^ gf_mul(a1, 0x0b) ^ gf_mul(a2, 0x0d) ^ gf_mul(a3, 0x09);
                s[c + 1] = gf_mul(a0, 0x09) ^ gf_mul(a1, 0x0e) ^ gf_mul(a2, 0x0b) ^ gf_mul(a3, 0x0d);
                s[c + 2] = gf_mul(a0, 0x0d) ^ gf_mul(a1, 0x09) ^ gf_mul(a2, 0x0e) ^ gf_mul(a3, 0x0b);
                s[c + 3] = gf_mul(a0, 0x0b) ^ gf_mul(a1, 0x0d) ^ gf_mul(a2, 0x09) ^ gf_mul(a3, 0x0e);
            }
        }
    }
    memcpy(out, s, 16);
}

/* ============================================================================
 * FIPS-180-4 SHA-1
 * ============================================================================ */

static inline uint32_t rol32(uint32_t v, unsigned int n) {
    return (v << n) | (v >> (32u - n));
}

static void sha1_block(uint32_t h[5], const uint8_t block[64]) {
    uint32_t w[80];
    for (int i = 0; i < 16; i++) {
        w[i] = ((uint32_t)block[i * 4 + 0] << 24) |
               ((uint32_t)block[i * 4 + 1] << 16) |
               ((uint32_t)block[i * 4 + 2] << 8)  |
               ((uint32_t)block[i * 4 + 3]);
    }
    for (int i = 16; i < 80; i++) {
        w[i] = rol32(w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16], 1u);
    }

    uint32_t a = h[0], b = h[1], c = h[2], d = h[3], e = h[4];
    for (int i = 0; i < 80; i++) {
        uint32_t f, k;
        if (i < 20) {
            f = (b & c) | ((~b) & d);
            k = 0x5A827999u;
        } else if (i < 40) {
            f = b ^ c ^ d;
            k = 0x6ED9EBA1u;
        } else if (i < 60) {
            f = (b & c) | (b & d) | (c & d);
            k = 0x8F1BBCDCu;
        } else {
            f = b ^ c ^ d;
            k = 0xCA62C1D6u;
        }
        uint32_t temp = rol32(a, 5u) + f + e + k + w[i];
        e = d;
        d = c;
        c = rol32(b, 30u);
        b = a;
        a = temp;
    }

    h[0] += a;
    h[1] += b;
    h[2] += c;
    h[3] += d;
    h[4] += e;
}

void sc21_sha1_compute(const void *data, size_t len, uint8_t digest[20]) {
    const uint8_t *p = (const uint8_t *)data;
    uint32_t h[5] = {
        0x67452301u,
        0xEFCDAB89u,
        0x98BADCFEu,
        0x10325476u,
        0xC3D2E1F0u,
    };

    size_t full_len = (len / 64u) * 64u;
    for (size_t off = 0; off < full_len; off += 64u) {
        sha1_block(h, p + off);
    }

    uint8_t tail[128];
    memset(tail, 0, sizeof(tail));
    size_t rem = len - full_len;
    if (rem > 0) {
        memcpy(tail, p + full_len, rem);
    }
    tail[rem] = 0x80u;

    size_t pad_blocks = (rem >= 56u) ? 2u : 1u;
    uint64_t bit_len = (uint64_t)len * 8ULL;
    size_t len_off = pad_blocks * 64u - 8u;
    for (int i = 0; i < 8; i++) {
        tail[len_off + (size_t)i] = (uint8_t)((bit_len >> ((7 - i) * 8)) & 0xFFu);
    }

    sha1_block(h, tail);
    if (pad_blocks == 2u) {
        sha1_block(h, tail + 64u);
    }

    for (int i = 0; i < 5; i++) {
        digest[i * 4 + 0] = (uint8_t)((h[i] >> 24) & 0xFFu);
        digest[i * 4 + 1] = (uint8_t)((h[i] >> 16) & 0xFFu);
        digest[i * 4 + 2] = (uint8_t)((h[i] >> 8)  & 0xFFu);
        digest[i * 4 + 3] = (uint8_t)(h[i] & 0xFFu);
    }
}
